"""국토부 CSV의 '시군구' 필드 파싱

두 적재 스크립트(load_csv.py, load_rent_csv.py)가 같은 규칙을 써야 해서 여기 모았다.
한쪽만 고치면 매매와 전월세의 단지 키가 어긋나 같은 아파트가 두 개로 갈라진다.
"""


def parse_sido_gu_dong(시군구: str):
    """'서울특별시 도봉구 방학동' → ('서울특별시', '도봉구', '방학동')

    이 필드는 항상 법정동(또는 리)으로 끝난다. 그래서 앞에서 세 토막을 자르면 안 되고
    **뒤에서부터** 잘라야 한다. 토막 수가 지역마다 다르기 때문이다.

      경기도 수원시 영통구 매탄동   4토막  시 아래 구가 있는 특례시
      서울특별시 강남구 개포동      3토막  특별·광역시
      경기도 의정부시 고산동        3토막  구 없는 시·군
      세종특별자치시 집현동         2토막  세종은 시군구 단계가 없다

    예전에는 parts[0], parts[1], parts[2]를 그대로 썼다. 그러면 수원시는
    ('경기도', '수원시', '영통구')가 되어 매탄동이 통째로 사라졌다.
    apts의 유일키가 (name, gu, dong, area_sqm)이라, 영통구 안 서로 다른 동에 같은
    이름 단지가 있으면 한 행으로 합쳐지고 거래가 뒤섞였다. 운영 데이터에서 이 모양인
    행이 21,284개(전체의 18.4%)였다.

    세종(2토막)은 gu를 시도와 같게 둔다. 국토부 기준으로 '세종특별자치시' 자체가
    시군구이기 때문이다. 화면에서 gu와 sido가 같으면 구를 표시하지 않는다.
    """
    parts = 시군구.strip().split()

    if len(parts) >= 3:
        # 가운데를 다 이어 붙인다. 4토막이면 '수원시 영통구'가 시군구가 된다.
        return parts[0], " ".join(parts[1:-1]), parts[-1]
    if len(parts) == 2:
        return parts[0], parts[0], parts[1]
    if len(parts) == 1:
        return parts[0], "", ""
    return "", "", ""
