-- 전월세는 전세·신규만 보관한다
--
-- ─── 왜 ────────────────────────────────────────────────────────────────────
-- apt_rent_prices 뷰가 deal_type='전세' and contract_type='신규'로 거른다. 즉
-- 월세와 갱신 계약은 저장·색인 비용만 내고 한 번도 읽히지 않는다. 앱에는 월세라는
-- 개념 자체가 없다 — 화면 문구도 "최근 전세", "최근 6개월간 전세 거래 내역이
-- 없습니다"이고, monthly_man은 유니크 제약에만 등장하며 contract_period는 어디에서도
-- 읽히지 않는다.
--
-- 운영 실측: 전월세 110만 행 중 약 60%가 그런 행이고, 인덱스까지 133MB였다.
-- 무료 플랜 500MB에서 그 비용을 낼 이유가 없다.
--
-- ⚠ 되돌리기: 국토부 시도별 조회가 366일까지라 그 안에 있는 것만 backfill.yml로
--   다시 받을 수 있다. 1년이 지나면 영구 소실이다. 월세 시세, 전월세 전환율,
--   갱신 계약 분석은 앞으로 만들 수 없다는 뜻이다 (2026-08-18에 그 조건으로 결정).
--
-- ⚠ scripts/load_rent_csv.py도 같이 고쳐야 한다. 안 그러면 다음 수집에서 그대로
--   다시 들어온다. (preprocess()의 전세·신규 필터)

-- ─── 1. 지우기 ─────────────────────────────────────────────────────────────
-- 실행 전에 얼마나 지워지는지 먼저 보고 싶다면:
--   select deal_type, contract_type, count(*)
--     from rent_transactions group by 1, 2 order by 3 desc;
--
-- contract_type이 NULL인 행도 지운다. 뷰의 '신규' 비교에서 어차피 탈락하므로
-- 저장해 둘 이유가 없다. (is distinct from은 NULL도 걸러 준다)
delete from rent_transactions
 where deal_type <> '전세'
    or contract_type is distinct from '신규';

-- 거래가 하나도 안 남은 단지는 어느 뷰에도 안 나오면서 자리만 차지한다.
-- apts는 행당 600바이트로 거래의 두 배가 넘는다. 다음 적재에서 그 단지의 거래가
-- 다시 들어오면 upsert가 되살린다.
delete from apts a
 where not exists (select 1 from transactions      t where t.apt_id = a.id)
   and not exists (select 1 from rent_transactions r where r.apt_id = a.id);

-- ─── 2. 공간 회수 ──────────────────────────────────────────────────────────
-- ⚠ 여기서부터는 이 파일을 통째로 실행하지 말고 한 줄씩 돌릴 것.
--   vacuum은 트랜잭션 안에서 못 돈다.
--
-- delete는 자리를 비워둘 뿐 파일을 줄이지 않는다. 평소에는 다음 적재가 그 자리를
-- 재사용하므로 그걸로 충분하지만, 지금은 무료 플랜 500MB를 넘긴 상태라 OS까지
-- 돌려받아야 한다. vacuum full은 테이블을 새로 쓰면서 인덱스도 함께 다시 만든다.
--
-- ⚠ 그동안 그 테이블을 통째로 잠근다. 다만 앱은 이 테이블들을 직접 읽지 않고
--   matview만 읽으므로 화면에는 영향이 없다. 수집이 도는 월·목 오전 10시(KST)만
--   피하면 된다.
--
-- ⚠ 새 테이블을 옆에 쓰는 만큼 여유 공간이 필요하다. 지운 뒤라 원본의 40% 수준
--   (약 90MB)이면 되지만, 작은 것부터 돌려 공간을 벌어 나가는 편이 안전하다.
--
-- vacuum full apts;
-- vacuum full rent_transactions;
--
-- 통계를 다시 만든다 (행수가 60% 줄어 플래너의 추정이 크게 어긋난 상태다).
-- analyze;

