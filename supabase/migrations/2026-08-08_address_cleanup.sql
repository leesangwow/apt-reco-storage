-- 주소 파싱 수정 이후 정리 — 옛 키로 들어간 행 삭제
--
-- ⚠ 이 SQL은 파서 수정 배포 + 재수집·재적재를 **마친 뒤에** 실행할 것.
--   순서를 지키지 않으면 화면에서 해당 지역이 통째로 비어 버린다.
--
-- 배경: 국토부 CSV의 '시군구'는 항상 법정동으로 끝나는데, 예전 파서가 앞에서 세
-- 토막을 잘라 쓰는 바람에 토막이 4개인 특례시에서 동이 사라졌다.
--
--   경기도 수원시 영통구 매탄동  →  gu='수원시', dong='영통구'   (매탄동 유실)
--   세종특별자치시 집현동        →  gu='집현동', dong=''         (한 칸 밀림)
--
-- apts의 유일키가 (name, gu, dong, area_sqm)이라, 동이 없어지면 같은 구 안 서로
-- 다른 동의 동명 단지가 한 행으로 합쳐져 거래가 뒤섞였다. 운영 실측:
--   전체 115,617행 중 dong 자리에 구가 든 행 21,284개 (18.4%), 세종 빈값 1,129개
--   동이 살아있는 4대 광역시 기준으로 "같은 구·같은 이름·다른 동"이 333건 719조합
--   → 특례시에서도 같은 비율로 병합이 일어나고 있었다
--
-- 파서를 고치면 같은 아파트가 새 키로 들어온다. 옛 행은 그대로 남아 화면에 중복으로
-- 보이므로 여기서 지운다. transactions·rent_transactions는 cascade로 함께 지워진다.
-- 수집이 최근 1년치를 받고 뷰는 6·12개월만 쓰므로 앱 기능에는 손실이 없다.

-- ─── 1. 먼저 무엇이 지워질지 확인 ───────────────────────────────────────────
-- 이 select를 먼저 돌려보고 숫자가 예상과 맞는지 볼 것.
-- '지울_옛행'이 0이면 재적재가 아직 안 끝난 것이다 — 삭제하지 말 것.
-- '남을_새행'이 0이면 재적재가 안 됐다는 뜻이니 역시 삭제하지 말 것.
select
  count(*) filter (where dong ~ '구$' and gu !~ ' ')                     as 지울_특례시_옛행,
  count(*) filter (where sido = '세종특별자치시' and dong = '')          as 지울_세종_옛행,
  count(*) filter (where gu ~ ' ')                                      as 남을_특례시_새행,
  count(*) filter (where sido = '세종특별자치시' and gu = sido)          as 남을_세종_새행,
  count(*)                                                              as 전체
from apts;

-- 지워질 것들을 눈으로 확인한다. dong이 전부 '○○구' 모양이어야 한다.
-- 만약 여기에 진짜 법정동(동·읍·면·리)이 섞여 있으면 삭제하지 말고 알릴 것.
select sido, gu, dong, count(*) as 행수
  from apts
 where (dong ~ '구$' and gu !~ ' ')
    or (sido = '세종특별자치시' and dong = '')
 group by 1, 2, 3
 order by 행수 desc
 limit 40;

-- ─── 2. 삭제 ────────────────────────────────────────────────────────────────
-- 새 파서는 특례시를 gu='수원시 영통구'(공백 포함), dong='매탄동'으로 넣는다.
-- 그래서 아래 조건은 옛 행만 정확히 고른다.
--   · dong이 '구'로 끝나는 행  → 옛 특례시 (새 행의 dong은 동·읍·면·리로 끝난다)
--   · 세종에서 dong이 빈 행     → 옛 세종  (새 행은 dong에 동 이름이 들어간다)
--
-- 혹시 모를 오탐을 막기 위해 gu에 공백이 없는 것(= 새 형식이 아닌 것)만 지운다.
delete from apts
 where (dong ~ '구$' and gu !~ ' ')
    or (sido = '세종특별자치시' and dong = '' );

-- ─── 3. 확인 ────────────────────────────────────────────────────────────────
-- 아래가 전부 0이어야 한다.
select
  count(*) filter (where dong ~ '구$' and gu !~ ' ')            as 남은_특례시_옛행,
  count(*) filter (where sido = '세종특별자치시' and dong = '')  as 남은_세종_옛행
from apts;

